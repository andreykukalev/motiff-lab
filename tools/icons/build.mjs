// The one icon set of both apps (0018 section 14): design/kit/icons.js, Andrei's, is the source. This writes
//   src/MotiffLab.Web/wwwroot/img/icons.svg       a sprite of <symbol id="ic-NAME">, drawn by the web app's Icon component
//   ipad/App/MotiffLab/Icons.xcassets/ic-NAME     one vector image per icon, a template the iPad app tints
// Run after changing the kit's icons:   node tools/icons/build.mjs
// tests/web/icons.test.mjs fails when the written files are not what the kit gives.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = fileURLToPath(new URL("../../", import.meta.url));

export const SPRITE = "src/MotiffLab.Web/wwwroot/img/icons.svg";
export const CATALOGUE = "ipad/App/MotiffLab/Icons.xcassets";

/** The kit's icons: name → the SVG body on the 20 px grid. */
export function readIcons(path = `${root}design/kit/icons.js`) {
    const code = readFileSync(path, "utf8");
    const icons = vm.runInNewContext(`${code}\n;ICONS`, {});
    return Object.fromEntries(Object.entries(icons).sort(([a], [b]) => a.localeCompare(b)));
}

/** The web sprite: every icon a symbol; the stroke comes from the .ic class, so icons take the colour of their text. */
export function sprite(icons) {
    const symbols = Object.entries(icons).map(([name, body]) => `  <symbol id="ic-${name}" viewBox="0 0 20 20">${body}</symbol>`);
    return [
        "<!-- Generated by tools/icons/build.mjs from design/kit/icons.js; do not edit. -->",
        '<svg xmlns="http://www.w3.org/2000/svg">',
        ...symbols,
        "</svg>",
        "",
    ].join("\n");
}

/** One icon as a file of its own, for the asset catalogue: black strokes that the app tints as a template. */
export function standalone(body) {
    const drawn = body.replaceAll('fill="currentColor"', 'fill="#000000"');
    return `<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 20 20" fill="none" stroke="#000000" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${drawn}</svg>\n`;
}

/** The asset catalogue's files: path inside the catalogue → content. */
export function catalogue(icons) {
    const info = { author: "xcode", version: 1 };
    const files = { "Contents.json": json({ info }) };
    for (const [name, body] of Object.entries(icons)) {
        files[`ic-${name}.imageset/ic-${name}.svg`] = standalone(body);
        files[`ic-${name}.imageset/Contents.json`] = json({
            images: [{ filename: `ic-${name}.svg`, idiom: "universal" }],
            info,
            properties: { "preserves-vector-representation": true, "template-rendering-intent": "template" },
        });
    }
    return files;
}

function json(value) {
    return `${JSON.stringify(value, null, 2)}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    const icons = readIcons();
    writeFileSync(`${root}${SPRITE}`, sprite(icons));
    rmSync(`${root}${CATALOGUE}`, { recursive: true, force: true });
    for (const [path, content] of Object.entries(catalogue(icons))) {
        const file = `${root}${CATALOGUE}/${path}`;
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, content);
    }
    console.log(`${Object.keys(icons).length} icons written to ${SPRITE} and ${CATALOGUE}`);
}
